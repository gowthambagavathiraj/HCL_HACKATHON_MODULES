CREATE TABLE employees (
    employee_id INT PRIMARY KEY,
    employee_name VARCHAR(100),
    department VARCHAR(50),
    salary DECIMAL(10,2)
);







PROBLEM STATEMENT
A company wants to maintain employee records. Every employee must have a unique employee ID that identifies the employee in the organization.
The system should store the employee ID, employee name, department, and salary.

TASK
Write a SQL statement to create the employees table with employee_id as the primary key.
